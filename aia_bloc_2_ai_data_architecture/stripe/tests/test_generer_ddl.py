def test_les_variantes_redshift_et_portable_se_distinguent_par_les_options_de_stockage():
    redshift, portable = g.ddl_olap("redshift"), g.ddl_olap("portable")
    exiger_options_redshift(redshift)
    exiger_variante_portable(portable)

    # Chaque variante est refusée par la règle de l'autre : elles ne se confondent pas.
    with pytest.raises(AssertionError):
        exiger_options_redshift(portable)
