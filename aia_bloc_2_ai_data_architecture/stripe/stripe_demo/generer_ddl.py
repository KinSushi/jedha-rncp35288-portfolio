INDEX_MONGO: tuple[tuple[str, dict[str, int], dict[str, Any]], ...] = (
    ("evenements", {"id_client": 1, "horodatage": -1}, {}),
    ("evenements", {"horodatage": 1}, {"expireAfterSeconds": 90 * 24 * 3600}),
    ("caracteristiques_clients", {"id_client": 1}, {"unique": True}),
    ("signaux_fraude", {"score": -1}, {}),
    ("signaux_fraude", {"id_paiement": 1}, {}),
    ("retours_clients", {"id_marchand": 1, "date": -1}, {}),
)


def schemas_mongo() -> dict[str, dict[str, Any]]:
    """Charge les validateurs JSON Schema (un fichier par collection, ordre alphabétique).

    Le JSON n'a pas de commentaires : la mention de droits d'auteur y est portée par la clé
    `_copyright`, retirée ici car elle n'a pas sa place dans un validateur MongoDB.
    """
    schemas = {}
    for fichier in sorted(DOSSIER_SCHEMAS.glob("*.json")):
        schema = json.loads(fichier.read_text(encoding="utf-8"))
        schema.pop("_copyright", None)
        schemas[fichier.stem] = schema
    return schemas


def script_collections_mongo() -> str:
    """Script mongosh : crée (ou met à jour) chaque collection avec son validateur et ses index."""
    schemas = schemas_mongo()
    corps = json.dumps(schemas, ensure_ascii=False, indent=2)
    index = "\n".join(
        f"base.{coll}.createIndex({json.dumps(cles)}, {json.dumps(options)});"
        for coll, cles, options in INDEX_MONGO)
    return f"""\
// {COPYRIGHT}
// Fichier GÉNÉRÉ par `python -m stripe_demo.generer_ddl` depuis nosql/schemas/*.json.
// Ne pas modifier à la main. Usage : mongosh "$URI_MONGO" nosql/creer_collections.js
// Exécution idempotente : une collection existante reçoit le validateur à jour (collMod).
// Remarque : $jsonSchema est une fonction de MongoDB ; pour Amazon DocumentDB, vérifier sa prise
// en charge avant bascule (à défaut, la validation reste applicative).

const base = db.getSiblingDB("stripe");

const schemas = {corps};

for (const [nom, schema] of Object.entries(schemas)) {{
  const options = {{
    validator: {{ $jsonSchema: schema }},
    validationLevel: "strict",   // tout document inséré ou modifié est contrôlé
    validationAction: "error",   // un document invalide est refusé (et non seulement signalé)
  }};
  if (base.getCollectionNames().includes(nom)) {{
    base.runCommand({{ collMod: nom, ...options }});
  }} else {{
    base.createCollection(nom, options);
  }}
}}

// Index (le champ TTL supprime automatiquement les événements de plus de 90 jours : RGPD).
{index}
"""


