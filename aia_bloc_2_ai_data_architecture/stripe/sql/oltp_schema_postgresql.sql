CREATE TABLE IF NOT EXISTS devises (
    code_devise VARCHAR(3) NOT NULL,
    nom VARCHAR(40) NOT NULL,
    decimales INTEGER NOT NULL,
    PRIMARY KEY (code_devise)
);

CREATE TABLE IF NOT EXISTS journal_audit (
    id_evenement BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    acteur VARCHAR(60) NOT NULL,
    action VARCHAR(30) NOT NULL,
    entite VARCHAR(30) NOT NULL,
    id_entite VARCHAR(40) NOT NULL,
    horodatage TIMESTAMP WITH TIME ZONE NOT NULL,
    details TEXT,
    PRIMARY KEY (id_evenement)
);

CREATE TABLE IF NOT EXISTS journal_changements (
    position INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    table_source VARCHAR(30) NOT NULL,
    operation VARCHAR(6) NOT NULL,
    id_ligne BIGINT NOT NULL,
    horodatage TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (position)
);

CREATE TABLE IF NOT EXISTS pays (
    code_pays VARCHAR(2) NOT NULL,
    nom VARCHAR(80) NOT NULL,
    region VARCHAR(20) NOT NULL,
    PRIMARY KEY (code_pays)
);

CREATE TABLE IF NOT EXISTS marchands (
    id_marchand BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    raison_sociale VARCHAR(120) NOT NULL,
    code_pays VARCHAR(2) NOT NULL,
    code_mcc VARCHAR(4) NOT NULL,
    statut VARCHAR(12) NOT NULL,
    cree_le TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id_marchand),
    CONSTRAINT ck_marchand_statut CHECK (statut IN ('actif', 'suspendu', 'ferme')),
    FOREIGN KEY(code_pays) REFERENCES pays (code_pays)
);

CREATE TABLE IF NOT EXISTS taux_change (
    code_devise VARCHAR(3) NOT NULL,
    date_taux DATE NOT NULL,
    taux_vers_usd NUMERIC(18, 8) NOT NULL,
    PRIMARY KEY (code_devise, date_taux),
    FOREIGN KEY(code_devise) REFERENCES devises (code_devise)
);

CREATE TABLE IF NOT EXISTS clients (
    id_client BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_marchand BIGINT NOT NULL,
    email_hache VARCHAR(64) NOT NULL,
    code_pays VARCHAR(2) NOT NULL,
    cree_le TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id_client),
    FOREIGN KEY(id_marchand) REFERENCES marchands (id_marchand),
    FOREIGN KEY(code_pays) REFERENCES pays (code_pays)
);

CREATE TABLE IF NOT EXISTS produits (
    id_produit BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_marchand BIGINT NOT NULL,
    nom VARCHAR(120) NOT NULL,
    prix_mineur BIGINT NOT NULL,
    code_devise VARCHAR(3) NOT NULL,
    periodicite VARCHAR(10),
    PRIMARY KEY (id_produit),
    FOREIGN KEY(id_marchand) REFERENCES marchands (id_marchand),
    FOREIGN KEY(code_devise) REFERENCES devises (code_devise)
);

CREATE TABLE IF NOT EXISTS abonnements (
    id_abonnement BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_client BIGINT NOT NULL,
    id_produit BIGINT NOT NULL,
    statut VARCHAR(12) NOT NULL,
    debut TIMESTAMP WITH TIME ZONE NOT NULL,
    fin TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (id_abonnement),
    CONSTRAINT ck_abonnement_statut CHECK (statut IN ('actif', 'impaye', 'annule')),
    FOREIGN KEY(id_client) REFERENCES clients (id_client),
    FOREIGN KEY(id_produit) REFERENCES produits (id_produit)
);

CREATE TABLE IF NOT EXISTS moyens_paiement (
    id_moyen BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_client BIGINT NOT NULL,
    type VARCHAR(12) NOT NULL,
    jeton_psp VARCHAR(40) NOT NULL,
    marque VARCHAR(12),
    quatre_derniers VARCHAR(4),
    pays_emission VARCHAR(2),
    PRIMARY KEY (id_moyen),
    CONSTRAINT ck_moyen_type CHECK (type IN ('carte', 'sepa', 'portefeuille')),
    FOREIGN KEY(id_client) REFERENCES clients (id_client),
    UNIQUE (jeton_psp),
    FOREIGN KEY(pays_emission) REFERENCES pays (code_pays)
);

CREATE TABLE IF NOT EXISTS paiements (
    id_paiement BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_marchand BIGINT NOT NULL,
    id_client BIGINT NOT NULL,
    id_moyen BIGINT NOT NULL,
    id_abonnement BIGINT,
    montant_mineur BIGINT NOT NULL,
    code_devise VARCHAR(3) NOT NULL,
    statut VARCHAR(12) NOT NULL,
    cree_le TIMESTAMP WITH TIME ZONE NOT NULL,
    pays_ip VARCHAR(2),
    appareil VARCHAR(10) NOT NULL,
    score_risque NUMERIC(5, 4),
    cle_idempotence VARCHAR(64) NOT NULL,
    PRIMARY KEY (id_paiement),
    CONSTRAINT ck_paiement_montant CHECK (montant_mineur > 0),
    CONSTRAINT ck_paiement_statut CHECK (statut IN ('reussi', 'echoue', 'rembourse', 'conteste')),
    CONSTRAINT ck_paiement_appareil CHECK (appareil IN ('mobile', 'ordinateur', 'tablette', 'api')),
    FOREIGN KEY(id_marchand) REFERENCES marchands (id_marchand),
    FOREIGN KEY(id_client) REFERENCES clients (id_client),
    FOREIGN KEY(id_moyen) REFERENCES moyens_paiement (id_moyen),
    FOREIGN KEY(id_abonnement) REFERENCES abonnements (id_abonnement),
    FOREIGN KEY(code_devise) REFERENCES devises (code_devise),
    FOREIGN KEY(pays_ip) REFERENCES pays (code_pays),
    UNIQUE (cle_idempotence)
);

CREATE INDEX IF NOT EXISTS ix_paiements_client_date ON paiements (id_client, cree_le);

CREATE INDEX IF NOT EXISTS ix_paiements_marchand_date ON paiements (id_marchand, cree_le);

CREATE TABLE IF NOT EXISTS litiges (
    id_litige BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_paiement BIGINT NOT NULL,
    motif VARCHAR(30) NOT NULL,
    statut VARCHAR(12) NOT NULL,
    cree_le TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id_litige),
    UNIQUE (id_paiement),
    FOREIGN KEY(id_paiement) REFERENCES paiements (id_paiement)
);

CREATE TABLE IF NOT EXISTS remboursements (
    id_remboursement BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_paiement BIGINT NOT NULL,
    montant_mineur BIGINT NOT NULL,
    motif VARCHAR(30) NOT NULL,
    cree_le TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id_remboursement),
    CONSTRAINT ck_remboursement_montant CHECK (montant_mineur > 0),
    FOREIGN KEY(id_paiement) REFERENCES paiements (id_paiement)
);

-- Documentation dans le catalogue
COMMENT ON TABLE paiements IS 'Transactions. Jamais de numéro de carte : uniquement le jeton du prestataire.';
COMMENT ON TABLE moyens_paiement IS 'Moyens de paiement tokenisés : jeton PSP et 4 derniers chiffres.';
COMMENT ON TABLE clients IS 'Clients des marchands. L''e-mail est stocké haché (pseudonymisation, RGPD).';
COMMENT ON TABLE journal_audit IS 'Journal d''audit en ajout seul : modification et suppression refusées.';
COMMENT ON TABLE journal_changements IS 'Journal d''« outbox » de la démonstration ; en production, Debezium lit le journal de transactions (WAL) et cette table reste vide.';

-- ------------------------------------------------------------------------------------------
-- Journal d'audit en ajout seul (PCI-DSS 10.3 : protéger les journaux contre toute
-- modification). Le propriétaire de la table pourrait supprimer le déclencheur : cette garde est
-- donc doublée en production par l'envoi des journaux vers un stockage à rétention verrouillée.
-- ------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION interdire_modification_audit() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'journal_audit est en ajout seul : % interdit', TG_OP
        USING ERRCODE = 'insufficient_privilege';
END
$$;

DROP TRIGGER IF EXISTS trg_audit_ajout_seul ON journal_audit;
CREATE TRIGGER trg_audit_ajout_seul BEFORE UPDATE OR DELETE ON journal_audit
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_audit();

DROP TRIGGER IF EXISTS trg_audit_pas_de_vidage ON journal_audit;
CREATE TRIGGER trg_audit_pas_de_vidage BEFORE TRUNCATE ON journal_audit
    FOR EACH STATEMENT EXECUTE FUNCTION interdire_modification_audit();

-- ------------------------------------------------------------------------------------------
-- Rôles au moindre privilège. Les rôles « groupe » ne se connectent pas (NOLOGIN) : les comptes
-- de service nominatifs en héritent. Sous Aurora, avec l'authentification IAM :
--     CREATE ROLE svc_application LOGIN;
--     GRANT rds_iam, role_application TO svc_application;  (idem svc_extraction, role_extraction)
-- Aucun mot de passe n'apparaît dans ce fichier.
-- ------------------------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_application') THEN
        CREATE ROLE role_application NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_cdc') THEN
        CREATE ROLE role_cdc NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_audit') THEN
        CREATE ROLE role_audit NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_extraction') THEN
        CREATE ROLE role_extraction NOLOGIN;
    END IF;
    -- Droit de répliquer : attribut REPLICATION sous PostgreSQL, rôle rds_replication sous Aurora.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rds_replication') THEN
        GRANT rds_replication TO role_cdc;
    ELSE
        ALTER ROLE role_cdc REPLICATION;
    END IF;
END
$$;

GRANT SELECT, INSERT ON marchands, clients, moyens_paiement, produits, abonnements, paiements,
    remboursements, litiges TO role_application;
GRANT SELECT ON pays, devises, taux_change TO role_application;
GRANT INSERT ON journal_audit TO role_application;
GRANT UPDATE (statut, score_risque) ON paiements TO role_application;
GRANT UPDATE (statut) ON marchands, litiges TO role_application;
GRANT UPDATE (statut, fin) ON abonnements TO role_application;
GRANT UPDATE (email_hache, code_pays) ON clients TO role_application;
GRANT SELECT ON marchands, clients, moyens_paiement, produits, abonnements, paiements, remboursements, litiges TO role_cdc;
GRANT SELECT ON journal_audit TO role_audit;
-- Extraction batch (rôle IAM « etl ») : lecture seule des tables métier et des référentiels.
GRANT SELECT ON marchands, clients, moyens_paiement, produits, abonnements, paiements, remboursements, litiges, pays, devises, taux_change TO role_extraction;

-- ------------------------------------------------------------------------------------------
-- Capture des changements (CDC) : publication logique lue par Debezium (plugin pgoutput).
-- Prérequis du serveur : wal_level = logical (Aurora : paramètre rds.logical_replication = 1).
-- Debezium est configuré avec publication.autocreate.mode = disabled : il n'a donc pas besoin
-- d'être propriétaire des tables.
-- ------------------------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'stripe_cdc') THEN
        CREATE PUBLICATION stripe_cdc FOR TABLE marchands, clients, moyens_paiement, produits, abonnements, paiements, remboursements, litiges;
    END IF;
END
$$;
