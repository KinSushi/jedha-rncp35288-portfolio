# Agrégats : vues matérialisées en production (rafraîchies automatiquement par Redshift),
# vues simples dans la variante portable. `FILTER (WHERE …)` n'étant pas pris en charge partout,
# on écrit `SUM(CASE WHEN … THEN … END)`, équivalent et portable.
AGREGATS = (
    ("agr_chiffre_quotidien", """\
SELECT d."date" AS "date", f.cle_marchand, COUNT(*) AS nb_paiements,
       SUM(CASE WHEN f.est_reussi THEN f.montant_usd END) AS chiffre_usd,
       AVG(CASE WHEN f.est_rembourse THEN 1.0 ELSE 0.0 END) AS taux_remboursement
FROM faits_paiements f JOIN dim_date d ON d.cle_date = f.cle_date
GROUP BY d."date", f.cle_marchand"""),
    ("agr_fraude_pays", """\
SELECT f.pays_ip, COUNT(*) AS nb_paiements,
       AVG(CASE WHEN f.est_conteste THEN 1.0 ELSE 0.0 END) AS taux_litige
FROM faits_paiements f
GROUP BY f.pays_ip"""),
)


def _nom(table: TableOlap, colonne: str) -> str:
    """Met entre guillemets les noms qui prêtent à confusion (voir TABLES_OLAP)."""
    return f'"{colonne}"' if colonne in table.mots_proteges else colonne


def _create_table(table: TableOlap, portable: bool) -> str:
    lignes = [f"    {_nom(table, nom)} {type_sql}{' NOT NULL' if obligatoire else ''}"
              for nom, type_sql, obligatoire in table.colonnes]
    lignes.append(f"    PRIMARY KEY ({_nom(table, table.cle_primaire)})")
    for colonne, cible, colonne_cible in table.cles_etrangeres:
        lignes.append(f"    FOREIGN KEY ({colonne}) REFERENCES {cible} ({colonne_cible})")
    options = "" if portable else f"\n{table.distribution}\n{table.tri}"
    return f"CREATE TABLE IF NOT EXISTS {table.nom} (\n" + ",\n".join(lignes) + f"\n){options};"


def _merge_faits() -> str:
    """Procédure d'application d'un micro-lot de faits (idempotente : rejouer ne duplique rien)."""
    faits = next(t for t in TABLES_OLAP if t.nom == "faits_paiements")
    noms = [c[0] for c in faits.colonnes]
    modifs = ",\n        ".join(f"{n} = s.{n}" for n in noms if n != "id_paiement")
    colonnes = textwrap.fill(", ".join(noms), 78, subsequent_indent="    ")
    valeurs = textwrap.fill(", ".join(f"s.{n}" for n in noms), 78, subsequent_indent="    ")
    return (
        "MERGE INTO faits_paiements\n"
        "USING stg_faits_paiements s ON faits_paiements.id_paiement = s.id_paiement\n"
        "WHEN MATCHED THEN UPDATE SET\n"
        f"        {modifs}\n"
        f"WHEN NOT MATCHED THEN INSERT (\n    {colonnes}\n)\n"
        f"VALUES (\n    {valeurs}\n);")


def ddl_olap(cible: str = "redshift") -> str:
    """DDL de l'entrepôt. `cible` : « redshift » (livrable) ou « portable » (tests dans DuckDB).

    Toute autre valeur est refusée : une faute de frappe ne doit pas produire, sans le dire, le
    DDL Redshift.
    """
    if cible not in ("redshift", "portable"):
        raise ValueError(f"cible inconnue : {cible!r} (attendu : 'redshift' ou 'portable')")
    portable = cible == "portable"
    entete = [f"-- {COPYRIGHT}",
              "-- Fichier GÉNÉRÉ par `python -m stripe_demo.generer_ddl` depuis la spécification "
              "TABLES_OLAP.",
              "-- Ne pas modifier à la main : modifier la spécification puis relancer le "
              "générateur."]
    if portable:
        entete.append("-- Variante portable (sans options Redshift), exécutée par les tests dans "
                      "DuckDB.")
    else:
        entete.extend([
            "-- Cible : Amazon Redshift (Serverless). Les contraintes PRIMARY KEY et FOREIGN KEY "
            "y sont",
            "-- informatives (non vérifiées) : elles guident l'optimiseur ; l'unicité est "
            "garantie par le",
            "-- MERGE de chargement ci-dessous. Montants en DECIMAL (exactitude) ; la "
            "démonstration",
            "-- DuckDB utilise DOUBLE. Ce DDL n'a pas été exécuté sur Redshift ; sa variante "
            "portable",
            "-- (sans options Redshift) l'est dans DuckDB par les tests.",
            "",
            "-- Distribution : les faits et la dimension client partagent la clé cle_client, "
            "ce qui",
            "-- co-localise leur jointure ; les petites dimensions sont copiées sur tous les "
            "nœuds",
            "-- (DISTSTYLE ALL). Tri : cle_date, car presque toutes les requêtes bornent la "
            "période."])
    blocs = ["\n".join(entete)]
    blocs.extend(_create_table(t, portable) for t in TABLES_OLAP)
    blocs.append("-- Agrégats pré-calculés : les tableaux de bord lisent peu de lignes.")
    for nom, requete in AGREGATS:
        if portable:
            blocs.append(f"CREATE VIEW {nom} AS\n{requete};")
        else:
            blocs.append(f"CREATE MATERIALIZED VIEW {nom} AUTO REFRESH YES AS\n{requete};")
    if not portable:
        blocs.append(
            "-- Table d'étape : le job de chargement y dépose chaque micro-lot (COPY depuis\n"
            "-- le lac S3, format Parquet), puis applique le MERGE ci-dessous. Rejouer un lot\n"
            "-- (reprise après panne) remplace les mêmes lignes : aucun doublon.\n"
            "CREATE TABLE IF NOT EXISTS stg_faits_paiements (LIKE faits_paiements);\n\n"
            "-- Procédure type (à exécuter par le job de chargement, après le COPY) :\n"
            + "\n".join(f"-- {ligne}" for ligne in _merge_faits().splitlines())
        )
        blocs.append(
            "-- Rôles de lecture (à exécuter une seule fois) : analystes et data science lisent\n"
            "-- l'étoile ; aucun des deux n'a accès à l'OLTP.\n"
            "CREATE ROLE role_analyste;\n"
            "CREATE ROLE role_data_science;\n"
            "GRANT SELECT ON ALL TABLES IN SCHEMA public TO ROLE role_analyste;\n"
            "GRANT SELECT ON ALL TABLES IN SCHEMA public TO ROLE role_data_science;")
    return _nettoyer("\n\n".join(blocs))


