def test_un_index_partiel_garde_sa_clause_where_dans_le_ddl_postgresql(monkeypatch):
    """Le DDL est compilé avec le dialecte PostgreSQL : sans lui, `WHERE ...` disparaîtrait."""
    modele = MetaData()
    Table("jeton", modele, Column("id", BigInteger, primary_key=True),
          Column("statut", String(10), nullable=False),
          Index("ix_jeton_actifs", "statut", postgresql_where=text("statut = 'actif'")))
    monkeypatch.setattr(m, "schema", modele)

    ddl = g.ddl_oltp_postgresql()

    exiger_index_partiel(ddl)
    with pytest.raises(AssertionError, match="index partiel"):  # la même base sans la clause
        exiger_index_partiel(ddl.replace(" WHERE statut = 'actif'", ""))


class IndexClasse(Index):
    """Index dont la place dans l'ensemble `table.indexes` est imposée par son rang.

    Un ensemble Python parcourt ses éléments dans l'ordre de leur hachage ; pour un objet ordinaire
    le hachage vient de l'adresse mémoire, donc l'ordre change d'une exécution à l'autre. Ici le
    hachage est le rang donné (0, 1, 2…) : l'ensemble les parcourt toujours dans cet ordre.
    """

    def __init__(self, nom, rang, *colonnes):
        # Le rang est posé avant le parent : l'index s'ajoute à l'ensemble de la table en naissant.
        self.rang = rang
        super().__init__(nom, *colonnes)

    def __hash__(self):
        return self.rang


def test_les_index_d_une_table_sont_ecrits_dans_l_ordre_alphabetique_de_leurs_noms(monkeypatch):
    """L'ordre ne doit pas dépendre de l'ensemble Python : sinon le fichier versionné changerait
    d'une exécution à l'autre et `--verifier` le jugerait périmé sans raison."""
    modele = MetaData()
    table = Table("jeton", modele, Column("id", BigInteger, primary_key=True),
                  Column("a", String(10)), Column("b", String(10)), Column("c", String(10)))
    # Rangs choisis à l'envers : l'ensemble parcourt ix_c, ix_b puis ix_a.
    for rang, nom in enumerate(["ix_c", "ix_b", "ix_a"]):
        IndexClasse(nom, rang, table.c[nom[-1]])  # rattaché à la table dès sa création
    assert [index.name for index in table.indexes] == ["ix_c", "ix_b", "ix_a"]
    monkeypatch.setattr(m, "schema", modele)

    ddl = g.ddl_oltp_postgresql()

    positions = [ddl.index(f"CREATE INDEX IF NOT EXISTS {nom} ON jeton") for nom in
                 ("ix_a", "ix_b", "ix_c")]
    assert positions == sorted(positions)


MERGE_ATTENDU = [
    "MERGE INTO faits_paiements",
    "USING stg_faits_paiements s ON faits_paiements.id_paiement = s.id_paiement",
    "WHEN MATCHED THEN UPDATE SET",
    "        colonne_0001 = s.colonne_0001,",
    "        colonne_0002 = s.colonne_0002,",
    "        colonne_0003 = s.colonne_0003,",
    "        colonne_0004 = s.colonne_0004,",
    "        neuf_cars = s.neuf_cars,",
    "        fin_de_liste = s.fin_de_liste",
    "WHEN NOT MATCHED THEN INSERT (",
    "    id_paiement, colonne_0001, colonne_0002, colonne_0003, colonne_0004,",
    "    neuf_cars, fin_de_liste",
    ")",
    "VALUES (",
    "    s.id_paiement, s.colonne_0001, s.colonne_0002, s.colonne_0003, s.colonne_0004,",
    "    s.neuf_cars, s.fin_de_liste",
    ");",
]


def test_le_merge_coupe_ses_listes_de_colonnes_a_78_caracteres_exactement(monkeypatch):
    """Sur des colonnes choisies pour que la coupure tombe pile : la liste des colonnes (68
    caractères + « neuf_cars, » ferait 79) s'arrête à 78, celle des valeurs (78 exactement)
    aussi ; une largeur de 79 ou de 70 ne donnerait pas les mêmes lignes."""
    faits = next(t for t in g.TABLES_OLAP if t.nom == "faits_paiements")
    noms = ["id_paiement", "colonne_0001", "colonne_0002", "colonne_0003", "colonne_0004",
            "neuf_cars", "fin_de_liste"]
    synthetique = dataclasses.replace(faits, colonnes=tuple((n, "BIGINT", True) for n in noms))
    monkeypatch.setattr(g, "TABLES_OLAP", tuple(
        synthetique if t.nom == "faits_paiements" else t for t in g.TABLES_OLAP))

    lignes = extraire_merge(g.ddl_olap("redshift"))

    exiger_merge(lignes, MERGE_ATTENDU)
    assert max(len(ligne.strip()) for ligne in lignes[9:]) == 78
    # Avec une coupure à 79 caractères, « neuf_cars, » monterait sur la première ligne.
    larges = [*MERGE_ATTENDU[:10],
              "    id_paiement, colonne_0001, colonne_0002, colonne_0003, colonne_0004, "
              "neuf_cars,",
              "    fin_de_liste", *MERGE_ATTENDU[12:]]
    with pytest.raises(AssertionError):
        exiger_merge(lignes, larges)


