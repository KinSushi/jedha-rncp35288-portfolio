def _nettoyer(sql: str) -> str:
    """Retire les espaces de fin de ligne et les tabulations : fichier lisible et stable."""
    lignes = [ligne.rstrip().replace("\t", "    ") for ligne in sql.splitlines()]
    return "\n".join(ligne for ligne in lignes) + "\n"


def _colonnes_identite(sql: str) -> str:
    """Remplace SERIAL/BIGSERIAL par des colonnes d'identité (norme SQL).

    Pourquoi : une colonne d'identité n'exige pas de droit distinct sur une séquence (l'INSERT
    suffit : moindre privilège) et reste liée à sa table. `BY DEFAULT` accepte aussi des
    identifiants imposés, comme ceux des données synthétiques de la démonstration.
    """
    sql = re.sub(r"\bBIGSERIAL\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY", sql)
    return re.sub(r"\bSERIAL\b", "INTEGER GENERATED BY DEFAULT AS IDENTITY", sql)


def ddl_oltp_postgresql() -> str:
    """DDL complet de l'OLTP pour PostgreSQL 16 / Aurora PostgreSQL."""
    dialecte = _dialecte_postgresql()
    blocs = [
        f"""-- {COPYRIGHT}
-- Fichier GÉNÉRÉ par `python -m stripe_demo.generer_ddl` depuis stripe_demo/modele_oltp.py.
-- Ne pas modifier à la main : modifier le modèle puis relancer le générateur.
-- Cible : PostgreSQL 16 (Aurora PostgreSQL compatible). Exécution idempotente.

-- ----------------------------------------------------------------------------------------
-- Tables, contraintes d'intégrité et index (dérivés du modèle SQLAlchemy)
-- ----------------------------------------------------------------------------------------"""
    ]
    for table in m.schema.sorted_tables:
        ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=dialecte))
        blocs.append(_colonnes_identite(ddl).strip() + ";")
        for index in sorted(table.indexes, key=lambda i: str(i.name)):
            blocs.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialecte))
                         .strip() + ";")
    commentaires = ["-- Documentation dans le catalogue"]
    for nom_table, texte in COMMENTAIRES_TABLES.items():
        protege = texte.replace("'", "''")  # l'apostrophe se double en SQL
        commentaires.append(f"COMMENT ON TABLE {nom_table} IS '{protege}';")
    blocs.append("\n".join(commentaires))
    blocs.append(COMPLEMENTS_OLTP)
    return _nettoyer("\n\n".join(blocs))


