@dataclass(frozen=True)
class TableOlap:
    """Spécification d'une table de l'entrepôt : colonnes, clés et options de stockage."""

    nom: str
    colonnes: tuple[tuple[str, str, bool], ...]  # (nom, type, obligatoire)
    cle_primaire: str
    cles_etrangeres: tuple[tuple[str, str, str], ...] = ()  # (colonne, table, colonne cible)
    distribution: str = "DISTSTYLE AUTO"
    tri: str = "SORTKEY AUTO"
    mots_proteges: frozenset[str] = field(default_factory=frozenset)


