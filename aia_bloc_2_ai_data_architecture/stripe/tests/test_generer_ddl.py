def test_la_specification_olap_est_celle_de_la_demonstration():
    """Même tables, mêmes colonnes, même ordre que `olap.DDL_ETOILE` : aucune divergence."""
    demo = duckdb.connect(":memory:")
    demo.execute(olap.DDL_ETOILE)
    exiger_specification_identique(g.TABLES_OLAP, demo)

    premiere = g.TABLES_OLAP[0]
    inversee = dataclasses.replace(premiere, colonnes=premiere.colonnes[::-1])
    with pytest.raises(AssertionError, match=premiere.nom):  # colonnes dans un autre ordre
        exiger_specification_identique((inversee, *g.TABLES_OLAP[1:]), demo)
    with pytest.raises(AssertionError):  # une table de moins
        exiger_specification_identique(g.TABLES_OLAP[:-1], demo)


