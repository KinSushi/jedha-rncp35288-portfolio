def exiger_fichier_a_jour(chemin: Path, attendu: str) -> None:
    assert chemin.exists(), f"{chemin.name} manquant : lancer le générateur"
    assert chemin.read_text(encoding="utf-8") == attendu, f"{chemin.name} périmé"


def exiger_ddl_oltp_fidele_au_modele(ddl: str) -> None:
    for table in m.schema.sorted_tables:
        assert f"CREATE TABLE IF NOT EXISTS {table.name} (" in ddl, table.name
        for contrainte in table.constraints:
            if isinstance(contrainte, CheckConstraint):
                assert f"CONSTRAINT {contrainte.name} CHECK" in ddl, contrainte.name
            if isinstance(contrainte, UniqueConstraint):
                assert "UNIQUE (" in ddl
        for index in table.indexes:
            assert f"CREATE INDEX IF NOT EXISTS {index.name} ON {table.name}" in ddl, index.name
    nb_fk = sum(len(t.foreign_keys) for t in m.schema.tables.values())
    assert len(re.findall(r"FOREIGN KEY\(", ddl)) == nb_fk
    # Les tables du modèle, ni plus ni moins, dans l'ordre des dépendances.
    assert re.findall(r"CREATE TABLE IF NOT EXISTS (\w+) \(", ddl) == [
        t.name for t in m.schema.sorted_tables]


def exiger_identite_sans_serial(ddl: str) -> None:
    assert not re.search(r"\b(BIG)?SERIAL\b", ddl), "SERIAL interdit : colonnes d'identité"
    assert "id_paiement BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL" in ddl


def exiger_publication_cdc(ddl: str) -> None:
    trouvee = re.search(r"CREATE PUBLICATION stripe_cdc FOR TABLE ([^;]+);", ddl)
    assert trouvee, "publication stripe_cdc absente"
    tables = tuple(t.strip() for t in trouvee.group(1).split(","))
    assert tables == g.TABLES_CDC
    assert set(g.TABLES_CDC) <= set(m.schema.tables)
    # Le journal d'audit et les journaux de la démonstration ne quittent jamais la base.
    assert not ({"journal_audit", "journal_changements"} & set(tables))


def exiger_aucun_secret(ddl: str) -> None:
    assert not re.search(r"(?i)\bpassword\b|\bmot_de_passe\b|\bsecret\b\s*=", ddl)
    assert not re.search(r"(?i)IDENTIFIED BY|ENCRYPTED PASSWORD", ddl)


def exiger_droits_au_moindre_privilege(droits: str) -> None:
    assert "DELETE" not in droits and "TRUNCATE" not in droits
    # Les montants ne sont jamais modifiables : seules les colonnes de statut et de score le sont.
    assert "GRANT UPDATE (statut, score_risque) ON paiements" in droits
    assert "montant_mineur" not in droits


def _colonnes_duckdb(cx, table: str) -> list[str]:
    return [ligne[0] for ligne in cx.execute(
        "SELECT column_name FROM information_schema.columns WHERE table_name = ? "
        "ORDER BY ordinal_position", [table]).fetchall()]


def exiger_specification_identique(tables, demo) -> None:
    for table in tables:
        assert [c[0] for c in table.colonnes] == _colonnes_duckdb(demo, table.nom), table.nom
    noms_demo = {r[0] for r in demo.execute(
        "SELECT table_name FROM information_schema.tables").fetchall()}
    assert {t.nom for t in tables} == noms_demo


def exiger_options_redshift(ddl: str) -> None:
    assert "DISTSTYLE KEY DISTKEY (cle_client)" in ddl
    assert "SORTKEY (cle_date)" in ddl
    assert ddl.count("CREATE MATERIALIZED VIEW") == len(g.AGREGATS)
    assert ddl.count("AUTO REFRESH YES") == len(g.AGREGATS)
    # Le MERGE de chargement (reproduit en commentaire dans le DDL) couvre toutes les colonnes
    # de la table de faits.
    faits = next(t for t in g.TABLES_OLAP if t.nom == "faits_paiements")
    merge = "\n".join(ligne for ligne in ddl.splitlines() if ligne.startswith("-- "))
    for nom, _type, _obligatoire in faits.colonnes:
        assert f"s.{nom}" in merge, nom
    assert "DECIMAL(18,4)" in ddl


def exiger_variante_portable(ddl: str) -> None:
    assert not re.search(r"DISTSTYLE|DISTKEY|SORTKEY|MATERIALIZED|AUTO REFRESH|MERGE", ddl)
    assert ddl.count("CREATE VIEW") == len(g.AGREGATS)


def exiger_index_partiel(ddl: str) -> None:
    assert ("CREATE INDEX IF NOT EXISTS ix_jeton_actifs ON jeton (statut) "
            "WHERE statut = 'actif';") in ddl, "clause WHERE de l'index partiel perdue"


def exiger_merge(lignes: list[str], attendu: list[str]) -> None:
    assert lignes == attendu


def extraire_merge(ddl: str) -> list[str]:
    """Les lignes du MERGE reproduit en commentaire (« -- »), sans leur préfixe."""
    commentaires = [ligne[3:] for ligne in ddl.splitlines() if ligne.startswith("-- ")]
    debut = commentaires.index("MERGE INTO faits_paiements")
    fin = commentaires.index(");", debut)
    return commentaires[debut:fin + 1]


def exiger_script_mongo(script: str) -> None:
    for nom in g.schemas_mongo():
        assert f'"{nom}": {{' in script, nom
    assert "_copyright" not in script  # clé propre aux fichiers JSON, absente du validateur
    assert script.startswith("// Copyright © 2026 · voir le fichier LICENSE du dépôt")


def exiger_index_declares(attendu: set, present: set) -> None:
    assert attendu <= present, f"index manquants : {attendu - present}"


