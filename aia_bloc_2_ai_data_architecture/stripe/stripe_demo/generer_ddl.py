def fichiers_generes() -> dict[Path, str]:
    """Chemin de chaque fichier généré et son contenu attendu."""
    return {
        FICHIER_OLTP: ddl_oltp_postgresql(),
        FICHIER_OLAP: ddl_olap("redshift"),
        FICHIER_MONGO: script_collections_mongo(),
    }


def main(argv: list[str] | None = None) -> int:
    parseur = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parseur.add_argument("--verifier", action="store_true",
                         help="ne rien écrire ; échouer si un fichier versionné est périmé")
    args = parseur.parse_args(argv)
    forcer_utf8()
    perimes = []
    for chemin, contenu in fichiers_generes().items():
        if args.verifier:
            actuel = chemin.read_text(encoding="utf-8") if chemin.exists() else None
            if actuel != contenu:
                perimes.append(chemin.name)
        else:
            chemin.parent.mkdir(parents=True, exist_ok=True)
            chemin.write_text(contenu, encoding="utf-8", newline="\n")
            print(f"écrit : {chemin.relative_to(RACINE)}")
    if perimes:
        print("fichiers périmés : " + ", ".join(perimes))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
