def test_les_index_de_la_demonstration_sont_dans_le_script_mongo():
    db = nosql.base()
    attendu = set()
    for collection in ("evenements", "caracteristiques_clients", "signaux_fraude"):
        for nom, info in db[collection].index_information().items():
            if nom != "_id_":
                attendu.add((collection, tuple(info["key"]), info.get("expireAfterSeconds"),
                             bool(info.get("unique"))))
    present = {(c, tuple(cles.items()), o.get("expireAfterSeconds"), bool(o.get("unique")))
               for c, cles, o in g.INDEX_MONGO}
    exiger_index_declares(attendu, present)

    assert attendu
    with pytest.raises(AssertionError, match="index manquants"):
        exiger_index_declares(attendu, present - {next(iter(attendu))})
