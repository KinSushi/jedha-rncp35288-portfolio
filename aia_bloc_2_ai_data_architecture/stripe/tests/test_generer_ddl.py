def test_le_ddl_oltp_reprend_toutes_les_tables_et_contraintes():
    ddl = g.ddl_oltp_postgresql()
    exiger_ddl_oltp_fidele_au_modele(ddl)

    contrainte_check = next(c.name for t in m.schema.sorted_tables for c in t.constraints
                            if isinstance(c, CheckConstraint) and c.name)
    index = next(i.name for t in m.schema.sorted_tables for i in t.indexes)
    premiere_table = m.schema.sorted_tables[0].name
    fautifs = {
        "une table renommée": ddl.replace(
            f"CREATE TABLE IF NOT EXISTS {premiere_table} (",
            f"CREATE TABLE IF NOT EXISTS {premiere_table}_bis (", 1),
        "une contrainte CHECK perdue": ddl.replace(
            f"CONSTRAINT {contrainte_check} CHECK", "CONSTRAINT sans_nom CHECK", 1),
        "un index perdu": ddl.replace(f"CREATE INDEX IF NOT EXISTS {index} ON",
                                      "CREATE INDEX IF NOT EXISTS autre ON", 1),
        "une clé étrangère perdue": ddl.replace("FOREIGN KEY(", "KEY(", 1),
        "une table de plus": ddl + "\nCREATE TABLE IF NOT EXISTS intruse (id INTEGER);\n",
    }
    for description, texte in fautifs.items():
        with pytest.raises(AssertionError):
            exiger_ddl_oltp_fidele_au_modele(texte)
        assert texte != ddl, description


